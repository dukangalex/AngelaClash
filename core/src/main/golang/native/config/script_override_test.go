func TestDisableManualSelectGroupParsesCleanly(t *testing.T) {
	raw, err := config.UnmarshalRawConfig([]byte(`
proxies:
  - name: node-a
    type: ss
    server: 1.1.1.1
    port: 443
    cipher: aes-128-gcm
    password: secret
proxy-groups:
  - name: 默认代理
    type: select
    proxies: [自动选择, 手动选择]
  - name: 手动选择
    type: select
    proxies: [node-a]
  - name: 自动选择
    type: url-test
    proxies: [node-a]
  - name: YouTube
    type: select
    proxies: [默认代理, 手动选择]
    default-selected: 手动选择
rules:
  - DOMAIN-SUFFIX,youtube.com,YouTube
  - MATCH,默认代理
`))
	if err != nil {
		t.Fatal(err)
	}
	groups := scriptGroups{
		rule: map[string]bool{
			"手动选择":      false,
			"自动选择":      true,
			"YouTube":   false,
			"生成地区自动选择组": true,
			"强制TUN":     true,
		},
	}
	applyRouting(raw, groups, false)
	for _, g := range raw.ProxyGroup {
		name, _ := g["name"].(string)
		if name == "手动选择" || name == "YouTube" || name == "生成地区自动选择组" || name == "强制TUN" {
			t.Fatalf("unexpected group remaining or created: %s", name)
		}
		if containsName(g["proxies"], "手动选择") {
			t.Fatalf("dangling reference to 手动选择 in group %s: %#v", name, g["proxies"])
		}
	}
	if _, err := config.ParseRawConfig(raw); err != nil {
		t.Fatalf("ParseRawConfig failed after disabling 手动选择: %v", err)
	}
}

func TestScriptReceivesToggledRuleOptions(t *testing.T) {
	raw, err := config.UnmarshalRawConfig([]byte(sampleProfile))
	if err != nil {
		t.Fatal(err)
	}
	script := `
const ruleOptionsEnable = {
  手动选择: true,
  YouTube: true,
};
let activeRuleOptions = ruleOptionsEnable;
function main(config, context) {
  if (context && context.customOptions) {
    activeRuleOptions = Object.assign({}, ruleOptionsEnable, context.customOptions);
  }
  const groups = [{ name: "默认代理", type: "select", proxies: ["node-a"] }];
  if (activeRuleOptions.手动选择) {
    groups.push({ name: "手动选择", type: "select", proxies: ["node-a"] });
    groups[0].proxies.push("手动选择");
  }
  config["proxy-groups"] = groups;
  config.rules = ["MATCH,默认代理"];
  return config;
}
`
	if err = applyScriptTextWithOptions(raw, script, map[string]bool{"手动选择": false, "UnknownKey": true}); err != nil {
		t.Fatal(err)
	}
	for _, g := range raw.ProxyGroup {
		if g["name"] == "手动选择" {
			t.Fatalf("disabled 手动选择 group should not have been generated by script")
		}
	}
}

func containsName(v any, name string) bool {
	switch list := v.(type) {
	case []string:
		for _, item := range list {
			if item == name {
				return true
			}
		}
	case []any:
		for _, item := range list {
			if item == name {
				return true
			}
		}
	}
	return false
}

